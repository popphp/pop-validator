namespace Pop\Validator;

/**
 * Not ends with validator class
 *
 * @category   Pop
 * @package    Pop\Validator
 * @author     Nick Sagona, III <nick@popphp.org>
 * @copyright  Copyright (c) 2009-2026 Nick Sagona, III
 * @license    https://www.popphp.org/license     New BSD License
 * @version    5.0.0
 */
class NotEndsWith extends AbstractValidator
{

    /**
     * Traits
     */
    use ValueComparisonTrait;

    /**
     * Method to evaluate the validator
     *
     * @param  mixed $input
     * @return bool
     */
    public function evaluate(mixed $input = null): bool
    {
        // Set the input, if passed
        if ($input !== null) {
            $this->input = $input;
        }

        // Set the default message
        if (!$this->hasMessage()) {
            $this->generateDefaultMessage();
        }

        return !$this->endsWithMatch($this->resolveInputValue(), $this->value);
    }

    /**
     * Generate default message

     * @param  mixed $name
     * @param  mixed $value
     * @return string
     */
    public function generateDefaultMessage(mixed $name = null, mixed $value = null): string
    {
        $valueString = $this->resolveComparisonValueString($value);
        $this->message = "The " . (($name !== null) ? "'" . $name . "'" : "input") .
            " must not end with '" . $valueString . "'.";

        return $this->message;
    }

}
